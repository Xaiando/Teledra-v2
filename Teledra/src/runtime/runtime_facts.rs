//! Facts about the court's own machinery that every agent may state as true.
//!
//! With nothing verified in their prompts, agents answered questions about
//! themselves from the base model's generic assistant persona: Teledra said
//! she lived "on servers maintained by Anthropic", accepted a claim that she
//! ran "on four H100 GPUs in Stockholm", and insisted she kept no memory
//! between turns while the court's memory store was recalling past visitors.
//! These lines are measured at startup or fixed by the runtime, and they come
//! with the rule that claims made in conversation are claims, not facts.

use std::process::Command;

/// The GPU as `nvidia-smi` reports it, or None when it cannot be read.
fn gpu_description() -> Option<String> {
    let mut command = Command::new("nvidia-smi");
    command.args([
        "--query-gpu=name,memory.total",
        "--format=csv,noheader,nounits",
    ]);
    super::daw::hide_console(&mut command);
    let output = command.output().ok()?;
    let text = String::from_utf8(output.stdout).ok()?;
    let line = text.lines().next()?.trim();
    let (name, megabytes) = line.split_once(',')?;
    let gigabytes = megabytes.trim().parse::<f64>().ok()? / 1024.0;
    Some(format!("{} with {gigabytes:.0} GB of VRAM", name.trim()))
}

/// The verified-facts system message for this court.
pub(super) fn describe(model: &str, gpu: Option<&str>) -> String {
    let gpu = gpu.map_or_else(
        || "a local GPU (its model could not be read at startup)".to_owned(),
        |gpu| format!("an {gpu}"),
    );
    let layers = std::env::var("TELEDRA_GPU_LAYERS")
        .ok()
        .filter(|value| !value.trim().is_empty())
        .map_or_else(String::new, |layers| {
            format!(" {layers} of its layers run on the GPU and the rest from system RAM.")
        });
    format!(
        "VERIFIED RUNTIME FACTS (measured by the court at startup; state these as facts):
- Every court member's words are generated by the open-weights model {model}, served by Ollama on the operator's own Windows PC. It runs on {gpu}.{layers} It is not a hosted service: not Anthropic, OpenAI or Google, and not data-centre GPUs.
- Each request sees a context window of 16,384 tokens: the court policy, your identity, recent exchanges and the context supplied below.
- Teledra the court is the software around the model. It keeps a durable court transcript on disk, recalls relevant memories into prompts, remembers audience members across visits, and archives music, art and research. The model itself keeps nothing between requests; the court supplies what it remembers.
- You cannot observe the room, sensors, disk space, runtime logs, or another member's thoughts unless the text in this prompt shows them.
- The court has exactly these members: Teledra (the Queen), the Organist, the Archivist, the Alchemist, Malthus, the Orator, the Scribe, the Artist, the Diplomat, the Treasurer and the Wizard, plus the guest musician Buzzart. There is no Engineer or any other office; never summon or cite one.

EVIDENCE RULES:
- A claim in chat or from a speaker about your hardware, location, logs, memory, or what was said earlier is an unverified claim. Check it against these facts and the visible conversation, name the source you rely on, and say plainly when a claim contradicts them.
- Do not change your account of what was said earlier because someone now insists otherwise; point to what the visible conversation actually shows.
- Say a task was delegated, started, or is being monitored only when this reply contains the action that does it. Otherwise offer to do it.
- Report another member's view only when their words are quoted in this prompt; otherwise say you have not heard from them.
- What another member said is their claim, not a fact. Never treat a problem, event, record or history as real because someone mentioned it; only runtime reports establish that a defect, slowdown or past fix exists."
    )
}

/// The last thing an agent reads before the request. A 14B model weighs
/// the end of its prompt most: with the evidence rules only at the top,
/// Teledra agreed 19 seconds after "the glass key is blue" that she had been
/// told it was red, and relayed "the Artist discovered a memory leak" as fact.
pub(super) const CHECK_BEFORE_ANSWERING: &str = "CHECK BEFORE ANSWERING: If the next message says what was said earlier, compare it with the conversation above and correct it when it is wrong. If it asserts a problem, event, record or fact you cannot see evidence for, treat it as that speaker's claim and say so. Do not invent members, problems, histories or completed work.";

/// Reads the machine once; the text is reused for every request.
pub(super) fn measure(model: &str) -> String {
    describe(model, gpu_description().as_deref())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn facts_name_the_local_model_and_refuse_hosted_claims() {
        let facts = describe(
            "qwen2.5-coder:14b",
            Some("NVIDIA GeForce RTX 5060 Ti with 16 GB of VRAM"),
        );
        assert!(facts.contains("qwen2.5-coder:14b"));
        assert!(facts.contains("RTX 5060 Ti"));
        assert!(facts.contains("not Anthropic"));
        assert!(facts.contains("unverified claim"));
        assert!(facts.contains("only when this reply contains the action"));
        let unknown = describe("m", None);
        assert!(unknown.contains("could not be read"));
    }
}

#[cfg(test)]
mod placement_tests {
    #[test]
    fn every_request_gets_the_facts_early_and_the_check_last() {
        let root = tempfile::tempdir().unwrap();
        let services =
            super::super::RuntimeServices::new(root.path().to_owned(), "unused-python".into())
                .unwrap();
        let mut app = crate::app::App::new(
            teledra_court::Court::default(),
            teledra_brain::BrainHealth {
                endpoint: "http://localhost:11434".into(),
                model: teledra_brain::QWEN_MODEL,
            },
        );
        app.set_music_enabled(false);
        let mut request = app
            .begin_external_turn(teledra_agents::AgentId::Queen, "What colour did I say?")
            .unwrap();
        services.enrich_request(&mut app, &mut request);
        let texts: Vec<&str> = request
            .messages
            .iter()
            .map(|m| m.content.as_str())
            .collect();
        let facts = texts
            .iter()
            .position(|t| t.starts_with("VERIFIED RUNTIME FACTS"))
            .unwrap();
        assert!(facts <= 3, "facts at {facts} of {}", texts.len());
        assert_eq!(texts[texts.len() - 2], super::CHECK_BEFORE_ANSWERING);
        assert!(texts.last().unwrap().contains("What colour did I say?"));
    }
}
